// ---- edge cases vs TS output ----

fn check(cases: &[(&str, &str, &str)], parse: impl Fn(&str) -> serde_json::Value) {
    for (name, html, expected) in cases {
        let expected: serde_json::Value = serde_json::from_str(expected).unwrap();
        assert_eq!(parse(html), expected, "case {name}");
    }
}

/// Header rows and rows without irn/title are dropped; first truthy SVL wins; last cover wins
/// (a placeholder-only img doesn't clear it); fields ignore a blank caption and overwrite
/// duplicates; actions are double-decoded, absolutized, deduped by href, and need a label;
/// only direct `span.d-block` children of `div.card-text` are lines; a nested `<tr>` clears
/// `current` (TS quirk), so the outer row loses its title; an implicitly closed `<tr>` still
/// runs its end handler at the enclosing close (rows come out inner-first); `total` falls back
/// to the item count and is null for a comma-only "of ,,".
#[test]
fn patron_items_edge_cases_match_ts() {
    check(PATRON_CASES, |html| {
        serde_json::to_value(parse_patron_items(html, ORIGIN)).unwrap()
    });
}

/// First matching link wins per kind; FMT is case-sensitive; non-OPAC links are ignored; the name
/// buffer resets on every matching element (last one wins) and an all-blank name is null.
#[test]
fn account_links_edge_cases_match_ts() {
    check(LINK_CASES, |html| {
        serde_json::to_value(parse_account_links(html, ORIGIN)).unwrap()
    });
}

