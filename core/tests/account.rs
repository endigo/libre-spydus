//! `parse::account` — golden parity with `middleware/src/parse/account.ts` (rows from
//! `tests/golden/MANIFEST.md`) plus edge cases whose expected JSON was produced by running the
//! TS parser (Bun HTMLRewriter) on the same HTML.
//!
